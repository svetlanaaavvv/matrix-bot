def get_archan(number):
    """Возвращает полные данные аркана по номеру"""
    return ARCHAN_MEANINGS.get(number, None)

def get_summary_text(archan_num):
    """Возвращает краткую сводку по аркану для главного меню"""
    archan = get_archan(archan_num)
    if not archan:
        return "Нет данных"
    
    name = archan.get("name", "")
    plus = archan.get("character", {}).get("plus", "")
    minus = archan.get("character", {}).get("minus", "")
    
    if len(plus) > 150:
        plus = plus[:150] + "..."
    
    return f"*{archan_num} Аркан {name}*\n✅ {plus}\n\n❌ {minus[:150] + '...' if len(minus) > 150 else minus}"